/** "On-site", "onsite", "on site" → ON_SITE. Anything unrecognised is refused, never guessed. */
export function normalizeMode(v: string): "ON_SITE" | "REMOTE" | "HYBRID" | null | "INVALID" {
  const s = v.trim().toLowerCase().replace(/[^a-z]/g, "");
  if (!s) return null;
  if (s === "onsite" || s === "inperson" || s === "office") return "ON_SITE";
  if (s === "remote" || s === "online" || s === "virtual") return "REMOTE";
  if (s === "hybrid") return "HYBRID";
  return "INVALID";
}

const normHeader = (h: string) =>
  h.replace(/^﻿/, "").trim().toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");

// ── Parsing ───────────────────────────────────────────────────────

type Cell = string | Date | null;
export type ParsedSheet = { headers: string[]; rows: Cell[][] };

/** RFC 4180 CSV: quoted fields, escaped quotes, CRLF/LF, BOM. */
export function parseCsv(text: string): ParsedSheet {
  const src = text.replace(/^﻿/, "");
  const out: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += ch;
      continue;
    }
    if (ch === '"' && field === "") quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      out.push(row);
      row = [];
      field = "";
    } else field += ch;
    if (out.length > MAX_ROWS + 1) break;
  }
  if (quoted) throw new CredentialError("The CSV has an unclosed quote.", "VALIDATION");
  if (field !== "" || row.length) {
    row.push(field);
    out.push(row);
  }
  const nonEmpty = out.filter((r) => r.some((c) => c.trim() !== ""));
  const [headers = [], ...rows] = nonEmpty;
  return { headers, rows };
}

function cellValue(v: ExcelJS.CellValue): Cell {
  if (v === null || v === undefined) return null;
  if (v instanceof Date) return v;
  if (typeof v === "string" || typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "object") {
    if ("richText" in v && Array.isArray(v.richText)) return v.richText.map((r) => r.text).join("");
    if ("text" in v && typeof v.text === "string") return v.text; // hyperlink
    if ("result" in v) return cellValue(v.result as ExcelJS.CellValue); // formula: use cached result only
  }
  return null;
}

export async function parseXlsx(bytes: Uint8Array): Promise<ParsedSheet> {
  const wb = new ExcelJS.Workbook();
  try {
    await wb.xlsx.load(Buffer.from(bytes) as unknown as ArrayBuffer);
  } catch {
    throw new CredentialError("That file could not be read as an Excel workbook.", "VALIDATION");
  }
  const ws = wb.worksheets[0];
  if (!ws) throw new CredentialError("The workbook has no sheets.", "VALIDATION");
  if (ws.rowCount > MAX_ROWS + 1) throw new CredentialError(`Too many rows (max ${MAX_ROWS} per upload).`, "VALIDATION");
  const all: Cell[][] = [];
  ws.eachRow({ includeEmpty: false }, (r) => {
    const cells: Cell[] = [];
    for (let c = 1; c <= Math.min(ws.columnCount, 30); c++) cells.push(cellValue(r.getCell(c).value));
    all.push(cells);
  });
  const [headerCells = [], ...rows] = all;
  return { headers: headerCells.map((h) => (h instanceof Date ? "" : String(h ?? ""))), rows };
}

export async function parseUpload(bytes: Uint8Array): Promise<ParsedSheet> {
  if (bytes.byteLength === 0) throw new CredentialError("The file is empty.", "VALIDATION");
  if (bytes.byteLength > MAX_FILE_BYTES) throw new CredentialError("The file is larger than 2 MB. Split it into smaller cohorts.", "VALIDATION");
  const isZip = bytes[0] === 0x50 && bytes[1] === 0x4b && bytes[2] === 0x03 && bytes[3] === 0x04;
  if (isZip) return parseXlsx(bytes);
  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    throw new CredentialError("Upload a CSV (UTF-8) or an .xlsx file.", "VALIDATION");
  }
  const sheet = parseCsv(text);
  if (sheet.rows.length > MAX_ROWS) throw new CredentialError(`Too many rows (max ${MAX_ROWS} per upload).`, "VALIDATION");
  return sheet;
}

// ── Normalization ─────────────────────────────────────────────────

/** Dates: ISO (YYYY-MM-DD), Indian DD/MM/YYYY or DD-MM-YYYY, or a real Excel date. Anything else is refused, never guessed. */
export function normalizeDate(v: Cell): string | null {
  if (v instanceof Date) {
    if (Number.isNaN(v.getTime())) return null;
    return toISODate(new Date(Date.UTC(v.getUTCFullYear(), v.getUTCMonth(), v.getUTCDate())));
  }
  const s = (v ?? "").trim();
  if (parseISODate(s)) return s;
  const m = /^(\d{1,2})[/.-](\d{1,2})[/.-](\d{4})$/.exec(s);
  if (m) {
    const iso = `${m[3]}-${m[2].padStart(2, "0")}-${m[1].padStart(2, "0")}`;
    return parseISODate(iso) ? iso : null;
  }
  return null;
}

const normText = (v: Cell) => (v instanceof Date ? "" : (v ?? "").normalize("NFC").replace(/\s+/g, " ").trim());

export type RowInput = {
  fullName: string;
  email: string;
  /** Course completions; for internships this is the end date. */
  completionDate: string;
  batchId: string | null;
  cohortName: string | null;
  externalRef: string | null;
  /** INTERNSHIP_COMPLETION rows: validated details, with the computed duration for the preview. */
  internship?: InternshipDetails | null;
};
export type RowMessage = { level: "error" | "warning"; text: string };

// ── Validation → job ──────────────────────────────────────────────

export async function createBulkJob(
  opts: { bytes: Uint8Array; fileName: string; courseId: string; defaultBatchId: string | null; sendEmail: boolean },
  actor: StaffUser,
  deps: CredentialDeps = defaultDeps(),
) {
  const { db } = deps;
  const course = await db.course.findUnique({ where: { id: opts.courseId }, include: { batches: true } });
  if (!course) throw new CredentialError("Program not found.", "NOT_FOUND");
  if (!course.code) throw new CredentialError("This program has no program code yet.", "CONFIG");
  const template = await db.certificateTemplate.findFirst({ where: { course_id: course.id, status: "ACTIVE" } });
  if (!template) throw new CredentialError("This program has no active certificate template.", "CONFIG");
  const credentialType = course.credential_type as CredentialType;
  const columns = bulkColumnsFor(credentialType);
  if (opts.defaultBatchId && !course.batches.some((b) => b.id === opts.defaultBatchId)) {
    throw new CredentialError("That cohort does not belong to this program.", "VALIDATION");
  }

  const sheet = await parseUpload(opts.bytes);
  const headers = sheet.headers.map((h) => HEADER_ALIASES[normHeader(h)] ?? normHeader(h));
  const forbidden = headers.filter((h) => (columns.forbidden as readonly string[]).includes(h));
  if (forbidden.length) {
    throw new CredentialError(`Remove the ${forbidden.join(", ")} column: certificate IDs and tokens are generated by the system.`, "VALIDATION");
  }
  const missing = (columns.required as readonly string[]).filter((r) => !headers.includes(r));
  if (missing.length) throw new CredentialError(`Missing required column(s): ${missing.join(", ")}. Download the template for the exact format.`, "VALIDATION");
  if (sheet.rows.length === 0) throw new CredentialError("The file has a header row but no learners.", "VALIDATION");
  const ignored = headers.filter((h) => (columns.ignored as readonly string[]).includes(h));
  const col = (name: string) => headers.indexOf(name);

  const spec = parseTemplateSpec(template);
  const today = indianDate(deps.now());
  const programTitle = course.certificate_title?.trim() || course.name;
  const batchByName = new Map(course.batches.map((b) => [b.name.trim().toLowerCase(), b]));
  const seen = new Map<string, number>();

  const rows: { row_number: number; input: RowInput; validation: "VALID" | "WARNING" | "ERROR"; messages: RowMessage[] }[] = [];
  for (let i = 0; i < sheet.rows.length; i++) {
    const r = sheet.rows[i];
    const rowNumber = i + 2; // spreadsheet row, header is row 1
    const get = (name: string) => (col(name) >= 0 ? r[col(name)] ?? null : null);
    const messages: RowMessage[] = [];
    const fullName = normText(get("full_name"));
    const email = normText(get("email")).toLowerCase();

    // Internship rows: the registry validates and computes the duration; the end date is the completion date.
    let internship: InternshipDetails | null = null;
    if (credentialType === "INTERNSHIP_COMPLETION") {
      const start = normalizeDate(get("start_date"));
      const end = normalizeDate(get("end_date"));
      const mode = normalizeMode(normText(get("mode")));
      if (!start) messages.push({ level: "error", text: "Start date must be YYYY-MM-DD or DD/MM/YYYY." });
      if (!end) messages.push({ level: "error", text: "End date must be YYYY-MM-DD or DD/MM/YYYY." });
      if (mode === "INVALID") messages.push({ level: "error", text: "Mode must be On-site, Remote or Hybrid." });
      if (start && end && mode !== "INVALID") {
        try {
          internship = buildInternshipDetails({
            internshipTitle: normText(get("internship_name")),
            department: normText(get("department")),
            startDate: start,
            endDate: end,
            totalHours: normText(get("total_hours")),
            supervisor: normText(get("supervisor")),
            mode,
            location: normText(get("location")),
          });
        } catch (e) {
          if (!(e instanceof z.ZodError)) throw e;
          for (const issue of e.issues) messages.push({ level: "error", text: issue.message });
        }
      }
    }
    const completionDate = credentialType === "INTERNSHIP_COMPLETION" ? (internship?.endDate ?? null) : normalizeDate(get("completion_date"));
    const programCode = normText(get("program_code")).toUpperCase();
    const cohortName = normText(get("cohort")) || null;
    const externalRef = normText(get("external_learner_ref")).slice(0, 120) || null;

    if (fullName.length < 2) messages.push({ level: "error", text: "Full name is missing." });
    if (fullName.length > 120) messages.push({ level: "error", text: "Full name is longer than 120 characters." });
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email) || email.length > 254) messages.push({ level: "error", text: "Email is missing or invalid." });
    if (credentialType === "INTERNSHIP_COMPLETION") {
      if (completionDate && parseISODate(completionDate)!.getTime() > today.getTime()) messages.push({ level: "error", text: "The internship end date is in the future." });
    } else if (!completionDate) messages.push({ level: "error", text: "Completion date must be YYYY-MM-DD or DD/MM/YYYY." });
    else if (parseISODate(completionDate)!.getTime() > today.getTime()) messages.push({ level: "error", text: "Completion date is in the future." });
    if (programCode && programCode !== course.code) messages.push({ level: "error", text: `Program code ${programCode} does not match ${course.code}.` });

    let batchId = opts.defaultBatchId;
    if (cohortName) {
      const b = batchByName.get(cohortName.toLowerCase());
      if (!b) messages.push({ level: "error", text: `Cohort “${cohortName}” does not exist for this program.` });
      else batchId = b.id;
    }
    if (ignored.length && i === 0) {
      messages.push({ level: "warning", text: `Column(s) ${ignored.join(", ")} are ignored; ${credentialType === "INTERNSHIP_COMPLETION" ? "duration and completion come from the start and end dates, and issue/expiry dates are set by the system" : "issue and expiry dates are set by the system"}.` });
    }

    const typeContext = internship ? internshipDedupeContext(internship) : null;
    const fileKey = `${email}|${typeContext ?? batchId ?? `date:${completionDate}`}`;
    if (email && seen.has(fileKey)) messages.push({ level: "error", text: `Duplicate of row ${seen.get(fileKey)} in this file.` });
    else if (email) seen.set(fileKey, rowNumber);

    if (!messages.some((m) => m.level === "error") && completionDate) {
      const student = await db.student.findFirst({ where: { email: { equals: email, mode: "insensitive" } } });
      if (student) {
        if (student.full_name.trim().toLowerCase() !== fullName.toLowerCase()) {
          messages.push({ level: "warning", text: `Existing learner is named “${student.full_name}”; the certificate will show “${fullName}”.` });
        }
        const key = dedupeKey({ studentId: student.id, courseId: course.id, batchId, completionDate: parseISODate(completionDate)!, typeContext });
        const existing = await db.credential.findFirst({ where: { dedupe_key: key, status: { in: ["ISSUING", "VALID"] } }, select: { certificate_id: true } });
        if (existing) messages.push({ level: "warning", text: `Already has active credential ${existing.certificate_id}. This row will be skipped as a duplicate.` });
      }
      const issues = await preflightCertificate(
        spec,
        {
          learnerName: fullName,
          programName: programTitle,
          completionDate: parseISODate(completionDate)!,
          issueDate: today,
          expiresOn: null,
          certificateId: generateCertificateId({ programCode: course.code, year: today.getUTCFullYear() }),
          verifyUrl: verificationUrl("x".repeat(22)),
          internship: internship
            ? {
                title: internship.internshipTitle,
                department: internship.department,
                startDate: parseISODate(internship.startDate)!,
                endDate: parseISODate(internship.endDate)!,
                duration: internship.duration.label,
                totalHours: internship.totalHours,
              }
            : undefined,
        },
        (p) => deps.storage.get(p),
      );
      for (const iss of issues) messages.push({ level: "error", text: `${iss.field === "learner_name" ? "Name" : iss.field}: ${iss.message}` });
    }

    const validation = messages.some((m) => m.level === "error") ? "ERROR" : messages.some((m) => m.level === "warning") ? "WARNING" : "VALID";
    rows.push({
      row_number: rowNumber,
      input: { fullName, email, completionDate: completionDate ?? "", batchId, cohortName, externalRef, internship },
      validation,
      messages,
    });
  }

  const job = await db.$transaction(async (tx) => {
    const j = await tx.credentialBulkJob.create({
      data: {
        course_id: course.id,
        batch_id: opts.defaultBatchId,
        template_id: template.id,
        file_name: opts.fileName.slice(0, 200),
        file_sha256: createHash("sha256").update(opts.bytes).digest("hex"),
        send_email: opts.sendEmail,
        credential_type: credentialType,
        total_rows: rows.length,
        created_by_id: actor.id,
      },
    });
    await tx.credentialBulkRow.createMany({
      data: rows.map((r) => ({
        job_id: j.id,
        row_number: r.row_number,
        input: r.input as unknown as Prisma.InputJsonValue,
        validation: r.validation,
        messages: r.messages as unknown as Prisma.InputJsonValue,
      })),
    });
    return j;
  });
  await db.auditLog.create({
    data: {
      actor_id: actor.id,
      action: "BULK_JOB_VALIDATED",
      entity_type: "credential_bulk_job",
      entity_id: job.id,
      after: { rows: rows.length, errors: rows.filter((r) => r.validation === "ERROR").length, file: job.file_name, sha256: job.file_sha256, credential_type: credentialType },
    },
  });
  return job;
}

export async function confirmBulkJob(jobId: string, actor: StaffUser, deps: CredentialDeps = defaultDeps()) {
  const { db } = deps;
  return db.$transaction(async (tx) => {
    const job = await tx.credentialBulkJob.findUnique({ where: { id: jobId } });
    if (!job) throw new CredentialError("Bulk job not found.", "NOT_FOUND");
    if (job.status !== "VALIDATED") return job; // already confirmed: confirming twice is harmless
    await tx.credentialBulkRow.updateMany({
      where: { job_id: jobId, validation: "ERROR", outcome: "PENDING" },
      data: { outcome: "SKIPPED", error: "Not issued: the row failed validation.", processed_at: new Date() },
    });
    const updated = await tx.credentialBulkJob.update({
      where: { id: jobId },
      data: { status: "PROCESSING", confirmed_by_id: actor.id, confirmed_at: new Date() },
    });
    await tx.auditLog.create({ data: { actor_id: actor.id, action: "BULK_JOB_CONFIRMED", entity_type: "credential_bulk_job", entity_id: jobId } });
    return updated;
  });
}

export async function cancelBulkJob(jobId: string, actor: StaffUser, deps: CredentialDeps = defaultDeps()) {
  const job = await deps.db.credentialBulkJob.findUnique({ where: { id: jobId } });
  if (!job) throw new CredentialError("Bulk job not found.", "NOT_FOUND");
  if (job.status !== "VALIDATED") throw new CredentialError("Only a job that has not been confirmed can be discarded.", "NOT_ALLOWED");
  await deps.db.credentialBulkJob.update({ where: { id: jobId }, data: { status: "CANCELLED" } });
  await deps.db.auditLog.create({ data: { actor_id: actor.id, action: "BULK_JOB_CANCELLED", entity_type: "credential_bulk_job", entity_id: jobId } });
}

const ROW_LEASE_MS = 2 * 60 * 1000;

/**
 * Issue up to `limit` pending rows. Rows are claimed with a short lease so two
 * concurrent callers work on different rows; even if a lease expires mid-row,
 * the deterministic idempotency key makes the second attempt resolve to the
 * same credential.
 */
export async function processBulkChunk(jobId: string, actor: StaffUser, deps: CredentialDeps = defaultDeps(), limit = 10) {
  const { db } = deps;
  const job = await db.credentialBulkJob.findUnique({ where: { id: jobId } });
  if (!job) throw new CredentialError("Bulk job not found.", "NOT_FOUND");
  if (job.status === "VALIDATED") throw new CredentialError("Confirm the job before issuing.", "NOT_ALLOWED");
  if (job.status === "CANCELLED") throw new CredentialError("This job was discarded.", "NOT_ALLOWED");

  const now = deps.now();
  const candidates = await db.credentialBulkRow.findMany({
    where: {
      job_id: jobId,
      outcome: "PENDING",
      validation: { not: "ERROR" },
      OR: [{ processed_at: null }, { processed_at: { lt: new Date(now.getTime() - ROW_LEASE_MS) } }],
    },
    orderBy: { row_number: "asc" },
    take: limit,
  });

  let processed = 0;
  for (const row of candidates) {
    const claim = await db.credentialBulkRow.updateMany({
      where: { id: row.id, outcome: "PENDING", OR: [{ processed_at: null }, { processed_at: { lt: new Date(now.getTime() - ROW_LEASE_MS) } }] },
      data: { processed_at: deps.now() },
    });
    if (claim.count === 0) continue;
    const input = row.input as unknown as RowInput;
    let outcome: "SUCCESS" | "FAILED" | "DUPLICATE" = "FAILED";
    let credentialId: string | null = null;
    let error: string | null = null;
    try {
      const r = await issueCredential(
        {
          fullName: input.fullName,
          email: input.email,
          courseId: job.course_id,
          batchId: input.batchId,
          ...(input.internship
            ? (() => {
                // The service recomputes the duration from the dates; only the inputs travel.
                const { duration: _computed, ...details } = input.internship;
                void _computed;
                return { credentialType: "INTERNSHIP_COMPLETION" as const, internship: details };
              })()
            : { completionDate: input.completionDate }),
          templateId: job.template_id,
          sendEmail: job.send_email,
          idempotencyKey: `bulk:${jobId}:${row.row_number}`,
        },
        actor,
        deps,
        { source: "BULK" },
      );
      credentialId = r.credential.id;
      if (r.credential.status === "VALID") outcome = "SUCCESS";
      else error = r.credential.last_error ?? "Certificate generation failed.";
    } catch (e) {
      if (e instanceof CredentialError) {
        outcome = e.code === "DUPLICATE" ? "DUPLICATE" : "FAILED";
        error = e.message;
      } else {
        console.error("[bulk] row failed", jobId, row.row_number, e);
        error = "Unexpected error while issuing this row.";
      }
    }
    await db.credentialBulkRow.update({ where: { id: row.id }, data: { outcome, credential_id: credentialId, error, processed_at: deps.now() } });
    processed++;
  }

  const remaining = await db.credentialBulkRow.count({ where: { job_id: jobId, outcome: "PENDING", validation: { not: "ERROR" } } });
  if (remaining === 0 && job.status !== "COMPLETED") {
    await db.credentialBulkJob.update({ where: { id: jobId }, data: { status: "COMPLETED", completed_at: deps.now() } });
  }
  return { processed, remaining };
}

/** Put FAILED rows back in the queue. SUCCESS rows are never touched. */
export async function retryFailedRows(jobId: string, actor: StaffUser, deps: CredentialDeps = defaultDeps()) {
  const { db } = deps;
  const n = await db.credentialBulkRow.updateMany({ where: { job_id: jobId, outcome: "FAILED" }, data: { outcome: "PENDING", processed_at: null } });
  if (n.count > 0) await db.credentialBulkJob.update({ where: { id: jobId }, data: { status: "PROCESSING", completed_at: null } });
  await db.auditLog.create({ data: { actor_id: actor.id, action: "BULK_JOB_RETRY", entity_type: "credential_bulk_job", entity_id: jobId, after: { rows: n.count } } });
  return n.count;
}

/** Neutralize spreadsheet formula injection in exported cells. */
export function csvCell(v: string | null | undefined): string {
  let s = v ?? "";
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export async function bulkResultsCsv(jobId: string, includePrivate: boolean, deps: CredentialDeps = defaultDeps()) {
  const rows = await deps.db.credentialBulkRow.findMany({
    where: { job_id: jobId },
    orderBy: { row_number: "asc" },
    include: { credential: { select: { certificate_id: true, verification_token: true, status: true } } },
  });
  const job = await deps.db.credentialBulkJob.findUniqueOrThrow({ where: { id: jobId }, select: { credential_type: true } });
  const intern = job.credential_type === "INTERNSHIP_COMPLETION";
  const header = [
    "row",
    "full_name",
    ...(includePrivate ? ["email"] : []),
    ...(intern ? ["internship_name", "start_date", "end_date", "duration"] : []),
    "outcome",
    "certificate_id",
    "verification_url",
    "message",
  ];
  const lines = [header.join(",")];
  for (const r of rows) {
    const input = r.input as unknown as RowInput;
    const messages = (r.messages as unknown as RowMessage[]).map((m) => m.text);
    const i = input.internship;
    lines.push(
      [
        String(r.row_number),
        csvCell(input.fullName),
        ...(includePrivate ? [csvCell(input.email)] : []),
        ...(intern ? [csvCell(i?.internshipTitle), csvCell(i?.startDate), csvCell(i?.endDate), csvCell(i?.duration.label)] : []),
        r.outcome,
        csvCell(r.credential?.status === "VALID" ? r.credential.certificate_id : ""),
        csvCell(r.credential?.status === "VALID" ? verificationUrl(r.credential.verification_token) : ""),
        csvCell([r.error, ...messages].filter(Boolean).join(" | ")),
      ].join(","),
    );
  }
  return lines.join("\r\n") + "\r\n";
}
