/**
 * Bulk (cohort) issuance:
 *   upload → parse → normalize → validate every row → preview → confirm →
 *   process in small chunks → row-level results → export.
 *
 * Nothing is issued before confirmation. Each row's idempotency key is
 * deterministic (bulk:<job>:<row>), so re-running a chunk, a double-click, a
 * second browser tab or a "retry failed rows" can never create a second
 * credential for a row that already succeeded.
 */

export const MAX_FILE_BYTES = 2 * 1024 * 1024;
export const MAX_ROWS = 1000;

export const BULK_COLUMNS = {
  required: ["full_name", "email", "completion_date"] as const,
  optional: ["program_code", "cohort", "external_learner_ref"] as const,
  /** Generated by the system; refused if present so nobody can pick their own IDs. */
  forbidden: ["certificate_id", "verification_token", "token"] as const,
  /** Accepted in the PRD's suggested schema but not honoured in MVP (would allow back-dating). */
  ignored: ["issue_date", "expires_at"] as const,
};

